/**
 * Generating `netlify.toml`, and keeping it honest when the project changes.
 *
 * Two properties matter more than any single line of output:
 *
 * 1. **Determinism.** The same facts must produce the same bytes, because "keep it updated
 *    when config changes" is only checkable if an unchanged project does not churn the
 *    file. The round-trip test (render → parse → equivalent settings) is the guard.
 * 2. **No silent overwrite.** A file carrying settings Larpable does not own must survive a
 *    sync untouched. That is asserted by comparing the bytes before and after, not by
 *    trusting the returned action name.
 */

import { describe, expect, it } from "vitest";

import { FakeEnvironment } from "@/env/fake-environment";
import { deriveFacts, type ProjectFacts, type ProjectSnapshot } from "@/netlify/facts";
import {
  parseNetlifyToml,
  planNetlifyConfig,
  renderNetlifyToml,
  settingsEquivalent,
  syncNetlifyConfig,
  unmanagedSettings,
  writeNetlifyConfig,
} from "@/netlify/generator";

function snapshot(files: Record<string, string | null>, functionEntries: string[] = []): ProjectSnapshot {
  return {
    files,
    rootEntries: Object.keys(files).filter((path) => files[path] !== null && !path.includes("/")),
    publicEntries: [],
    functionEntries,
  };
}

const REACT_BUN = snapshot({
  "package.json": JSON.stringify({ scripts: { build: "vite build" }, dependencies: { react: "^18" } }),
  "vite.config.ts": "export default {};",
  "index.html": "<div id=app>",
  "bun.lock": "",
});

function factsOf(snap: ProjectSnapshot, hints = {}): ProjectFacts {
  return deriveFacts(snap, hints);
}

async function environment(tree: Record<string, string> = {}): Promise<FakeEnvironment> {
  const env = new FakeEnvironment({ tree });
  await env.initialize();
  return env;
}

async function text(env: FakeEnvironment, path: string): Promise<string | null> {
  try {
    return new TextDecoder().decode(await env.readFile(path));
  } catch {
    return null;
  }
}

describe("planNetlifyConfig", () => {
  it("generates PRD §8.1's default for Vite + React on Bun, plus the measured version pin", () => {
    const facts = factsOf(REACT_BUN, { packageManagerVersion: "1.4.5" });
    const plan = planNetlifyConfig(facts);

    expect(plan.problems).toEqual([]);
    expect(plan.toml).toBe(
      [
        "# netlify.toml — generated by Larpable from this project's own configuration.",
        "#",
        "# Framework: vite-react (`vite.config.ts` and on `react`.)",
        "# Package manager: bun (`bun.lock` is the project's lockfile.)",
        "#",
        "# Edit the project, not this file: regenerate it and validate it again, so the",
        "# configuration keeps matching what the project actually builds.",
        "",
        "[build]",
        '  command = "bun run build"',
        '  publish = "dist"',
        "",
        "[build.environment]",
        '  BUN_VERSION = "1.4.5"',
        "",
        "[[redirects]]",
        '  from = "/*"',
        '  to = "/index.html"',
        "  status = 200",
        "",
      ].join("\n"),
    );
    expect(plan.decisions.join("\n")).toContain("Publish directory `dist`");
    expect(plan.decisions.join("\n")).toContain("SPA fallback");
  });

  it("writes the command of the detected manager, not Bun by default", () => {
    const npmFacts = factsOf(
      snapshot({
        "package.json": JSON.stringify({ scripts: { build: "vite build" }, dependencies: { react: "^18" } }),
        "vite.config.ts": "export default {};",
        "index.html": "",
        "package-lock.json": "{}",
      }),
    );
    const plan = planNetlifyConfig(npmFacts);
    expect(plan.settings.build.command).toBe("npm run build");
    expect(plan.settings.build.environment).toBeUndefined();
    expect(plan.toml).not.toContain("BUN_VERSION");
  });

  it("gives a static site no command and no fallback", () => {
    const plan = planNetlifyConfig(factsOf(snapshot({ "index.html": "<h1>hi</h1>", "about.html": "<h1>a</h1>" })));

    expect(plan.settings.build.command).toBeUndefined();
    expect(plan.settings.build.publish).toBe(".");
    expect(plan.settings.redirects).toEqual([]);
    expect(plan.toml).not.toContain("[[redirects]]");
  });

  it("gives Astro no fallback", () => {
    const plan = planNetlifyConfig(
      factsOf(
        snapshot({
          "package.json": JSON.stringify({ scripts: { build: "astro build" }, dependencies: { astro: "^5" } }),
          "astro.config.mjs": "export default {};",
          "bun.lock": "",
        }),
      ),
    );
    expect(plan.settings.redirects).toEqual([]);
    expect(plan.settings.build.command).toBe("bun run build");
  });

  it("includes [functions] only when the project has functions", () => {
    const withFunctions = planNetlifyConfig(factsOf(REACT_BUN, {}), );
    expect(withFunctions.settings.functions).toBeUndefined();

    const functions = planNetlifyConfig(factsOf({ ...REACT_BUN, functionEntries: ["hello.mts"] }));
    expect(functions.settings.functions).toEqual({ directory: "netlify/functions" });
    expect(functions.toml).toContain("[functions]");
  });

  it("produces the same bytes for the same facts", () => {
    const first = planNetlifyConfig(factsOf(REACT_BUN, { packageManagerVersion: "1.4.5" }));
    const second = planNetlifyConfig(factsOf(REACT_BUN, { packageManagerVersion: "1.4.5" }));
    expect(first.toml).toBe(second.toml);
  });

  it("round-trips through a real TOML parser", () => {
    const plan = planNetlifyConfig(factsOf(REACT_BUN, { packageManagerVersion: "1.4.5" }));
    const parsed = parseNetlifyToml(plan.toml);

    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    expect(parsed.settings.build?.command).toBe("bun run build");
    expect(parsed.settings.build?.publish).toBe("dist");
    expect(parsed.settings.build?.environment).toEqual({ BUN_VERSION: "1.4.5" });
    expect(parsed.settings.redirects).toEqual([{ from: "/*", to: "/index.html", status: 200 }]);
    expect(settingsEquivalent(parsed.settings, plan.settings)).toBe(true);
  });

  it("refuses to render settings for facts with a problem", () => {
    const unknown = factsOf(snapshot({ "package.json": JSON.stringify({ scripts: { build: "vite build" } }) }));
    const plan = planNetlifyConfig(unknown);
    expect(plan.problems.length).toBeGreaterThan(0);
    expect(plan.problems.join(" ")).toContain("framework could not be identified");
    // The command is still reported (the facts have one), but no fallback was invented for
    // a framework that could not be identified — §8.3's "hardcoded assumption" ban.
    expect(plan.decisions.join(" ")).toContain("No SPA fallback");
  });
});

describe("renderNetlifyToml", () => {
  it("escapes a quote rather than emitting invalid TOML", () => {
    const toml = renderNetlifyToml({
      build: { command: 'echo "hi" && vite build', publish: "dist" },
      redirects: [],
    });

    const parsed = parseNetlifyToml(toml);
    expect(parsed.ok).toBe(true);
    if (parsed.ok) expect(parsed.settings.build?.command).toBe('echo "hi" && vite build');
  });
});

describe("parseNetlifyToml", () => {
  it("reports broken TOML as an error instead of guessing", () => {
    const parsed = parseNetlifyToml("[build\n  publish = 'dist'");
    expect(parsed.ok).toBe(false);
    if (!parsed.ok) expect(parsed.error.length).toBeGreaterThan(0);
  });

  it("keeps an invalid status as NaN so the validator can name it", () => {
    const parsed = parseNetlifyToml('[[redirects]]\nfrom = "/*"\nto = "/index.html"\nstatus = "gone"');
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    expect(Number.isNaN(parsed.settings.redirects?.[0]?.status)).toBe(true);
  });
});

describe("unmanagedSettings", () => {
  it("recognises the SPA fallback as its own", () => {
    const parsed = parseNetlifyToml('[build]\npublish = "dist"\n\n[[redirects]]\nfrom = "/*"\nto = "/index.html"\nstatus = 200');
    expect(parsed.ok).toBe(true);
    if (parsed.ok) expect(unmanagedSettings(parsed.raw)).toEqual([]);
  });

  it("names headers, contexts, plugins and application redirects", () => {
    const parsed = parseNetlifyToml(
      [
        "[build]",
        '  publish = "dist"',
        '  base = "apps/site"',
        "[[headers]]",
        '  for = "/*"',
        '[[redirects]]',
        '  from = "/api/*"',
        '  to = "/.netlify/functions/:splat"',
        "  status = 200",
        "[context.deploy-preview]",
        '  command = "npm run build"',
      ].join("\n"),
    );
    expect(parsed.ok).toBe(true);
    if (!parsed.ok) return;
    const unmanaged = unmanagedSettings(parsed.raw);
    expect(unmanaged).toContain("[headers]");
    expect(unmanaged).toContain("[context]");
    expect(unmanaged).toContain("[build].base");
    expect(unmanaged.join(" ")).toContain("/api/*");
  });
});

describe("writeNetlifyConfig", () => {
  it("writes the file at the project root", async () => {
    const env = await environment({ "package.json": "{}" });
    const plan = planNetlifyConfig(factsOf(REACT_BUN, { packageManagerVersion: "1.4.5" }));

    const written = await writeNetlifyConfig(env, plan);

    expect(written.path).toBe("/workspace/netlify.toml");
    expect(written.relativePath).toBe("netlify.toml");
    expect(written.bytes).toBeGreaterThan(0);
    expect(await text(env, "/workspace/netlify.toml")).toBe(plan.toml);
  });

  it("refuses to write a plan that could not be justified", async () => {
    const env = await environment({});
    const plan = planNetlifyConfig(factsOf(snapshot({ "package.json": "{}" })));
    await expect(writeNetlifyConfig(env, plan)).rejects.toThrow(/refusing to write/);
    expect(await text(env, "/workspace/netlify.toml")).toBeNull();
  });
});

describe("syncNetlifyConfig", () => {
  const facts = factsOf(REACT_BUN, { packageManagerVersion: "1.4.5" });

  it("writes when there is no file, and validates as written", async () => {
    const env = await environment({ "package.json": "{}" });
    const outcome = await syncNetlifyConfig(env, facts);

    expect(outcome.action).toBe("written");
    expect(outcome.before).toBeNull();
    expect(outcome.reason).toContain("there was none");
    expect(await text(env, "/workspace/netlify.toml")).toBe(outcome.plan.toml);
  });

  it("leaves an equivalent hand-formatted file byte-for-byte alone", async () => {
    const handWritten = [
      "# written by hand; formatting is not a reason to rewrite",
      "[build]",
      '  publish = "dist"',
      '  command = "bun run build"',
      "",
      "[build.environment]",
      "  BUN_VERSION = '1.4.5'",
      "",
      "[[redirects]]",
      '  from = "/*"',
      '  to = "/index.html"',
      "  status = 200",
      "",
    ].join("\n");
    const env = await environment({ "package.json": "{}", "netlify.toml": handWritten });

    const outcome = await syncNetlifyConfig(env, facts);

    expect(outcome.action).toBe("unchanged");
    expect(await text(env, "/workspace/netlify.toml")).toBe(handWritten);
  });

  it("updates a stale file when the project changed", async () => {
    const stale = '[build]\n  command = "npm run build"\n  publish = "build"\n';
    const env = await environment({ "package.json": "{}", "netlify.toml": stale });

    const outcome = await syncNetlifyConfig(env, facts);

    expect(outcome.action).toBe("written");
    expect(outcome.before).toBe(stale);
    const after = await text(env, "/workspace/netlify.toml");
    expect(after).toContain('command = "bun run build"');
    expect(after).toContain('publish = "dist"');
  });

  it("updates the command when the package manager changes from npm to Bun", async () => {
    const npmFacts = factsOf(
      snapshot({
        "package.json": JSON.stringify({ scripts: { build: "vite build" }, dependencies: { react: "^18" } }),
        "vite.config.ts": "export default {};",
        "index.html": "",
        "package-lock.json": "{}",
      }),
    );
    const env = await environment({
      "package.json": "{}",
      "netlify.toml": planNetlifyConfig(npmFacts).toml,
    });

    const outcome = await syncNetlifyConfig(env, facts);
    expect(outcome.action).toBe("written");
    expect(await text(env, "/workspace/netlify.toml")).toContain('command = "bun run build"');
  });

  it("preserves a file with settings Larpable does not manage", async () => {
    const withHeaders = [
      "[build]",
      '  command = "npm run build"',
      '  publish = "build"',
      "",
      "[[headers]]",
      '  for = "/*"',
      "  [headers.values]",
      '    X-Frame-Options = "DENY"',
      "",
    ].join("\n");
    const env = await environment({ "package.json": "{}", "netlify.toml": withHeaders });

    const outcome = await syncNetlifyConfig(env, facts);

    expect(outcome.action).toBe("preserved");
    expect(outcome.reason).toContain("[headers]");
    expect(await text(env, "/workspace/netlify.toml")).toBe(withHeaders);
  });

  it("replaces a file that is not valid TOML, because it cannot deploy either way", async () => {
    const broken = "[build\n  publish = 'dist'\n";
    const env = await environment({ "package.json": "{}", "netlify.toml": broken });

    const outcome = await syncNetlifyConfig(env, facts);

    expect(outcome.action).toBe("written");
    expect(outcome.reason).toContain("not valid TOML");
    expect(await text(env, "/workspace/netlify.toml")).toBe(outcome.plan.toml);
  });

  it("blocks instead of writing when the project cannot justify a configuration", async () => {
    const env = await environment({ "package.json": JSON.stringify({ scripts: { build: "vite build" } }) });
    const unknown = factsOf(snapshot({ "package.json": JSON.stringify({ scripts: { build: "vite build" } }) }));

    const outcome = await syncNetlifyConfig(env, unknown);

    expect(outcome.action).toBe("blocked");
    expect(outcome.reason).toContain("framework could not be identified");
    expect(await text(env, "/workspace/netlify.toml")).toBeNull();
  });

  it("writes into an explicit project root when the project is not the whole workspace", async () => {
    const rootFacts = factsOf(
      snapshot({
        "package.json": JSON.stringify({ scripts: { build: "vite build" }, dependencies: { vue: "^3" } }),
        "vite.config.ts": "export default {};",
        "index.html": "",
        "pnpm-lock.yaml": "",
      }),
    );
    const env = await environment({ "apps/site/package.json": "{}" });

    const outcome = await syncNetlifyConfig(env, rootFacts, { root: "/workspace/apps/site" });

    expect(outcome.path).toBe("/workspace/apps/site/netlify.toml");
    expect(await text(env, "/workspace/apps/site/netlify.toml")).toContain('command = "pnpm build"');
  });
});
