/**
 * Markdown rendering for the feasibility report.
 *
 * Kept pure and separate from the probes so the report format is testable without
 * booting a kernel: a report that silently drops a failure is worse than no report.
 */

export type ProbeStatus = "pass" | "fail" | "skipped";

export interface ProbeResult {
  /** Stable id used in the report anchor and in test assertions. */
  id: string;
  title: string;
  status: ProbeStatus;
  /** One-line verdict, no newlines. */
  detail: string;
  durationMs?: number;
  /** Captured command output, truncated by the renderer. */
  output?: string;
}

export interface ReportMeta {
  generatedAt: string;
  unkernelVersion: string;
  hostNode: string;
  hostPlatform: string;
  distroImage?: string;
  distroSha256?: string;
  guestKernel?: string;
  guestMemoryMiB?: number;
  totalMs?: number;
}

const MAX_OUTPUT_LINES = 30;
const MAX_OUTPUT_CHARS = 2_000;

function cell(text: string): string {
  return text.replaceAll("|", "\\|").replace(/\s*\n\s*/g, " ");
}

function truncate(output: string): string {
  const lines = output.split("\n");
  let text = lines.slice(0, MAX_OUTPUT_LINES).join("\n");
  if (text.length > MAX_OUTPUT_CHARS) text = `${text.slice(0, MAX_OUTPUT_CHARS)}\n…`;
  if (lines.length > MAX_OUTPUT_LINES) text += `\n… (${lines.length - MAX_OUTPUT_LINES} more lines)`;
  return text.trimEnd();
}

function marker(status: ProbeStatus): string {
  if (status === "pass") return "PASS";
  if (status === "fail") return "FAIL";
  return "SKIP";
}

export function renderReport(meta: ReportMeta, probes: readonly ProbeResult[]): string {
  const passed = probes.filter((probe) => probe.status === "pass").length;
  const failed = probes.filter((probe) => probe.status === "fail").length;
  const skipped = probes.filter((probe) => probe.status === "skipped").length;

  const lines: string[] = [
    "# unkernel feasibility report",
    "",
    "Generated by `bun run feasibility`. Every value below was captured by running the",
    "probes on the machine that produced this file — nothing here is written by hand.",
    "",
    "## Environment",
    "",
    "| Field | Value |",
    "| --- | --- |",
    `| Generated at | ${cell(meta.generatedAt)} |`,
    `| unkernel | ${cell(meta.unkernelVersion)} |`,
    `| Host Node | ${cell(meta.hostNode)} |`,
    `| Host platform | ${cell(meta.hostPlatform)} |`,
    `| Distro image | ${cell(meta.distroImage ?? "not used")} |`,
    `| Distro SHA-256 | ${cell(meta.distroSha256 ?? "not used")} |`,
    `| Guest kernel | ${cell(meta.guestKernel ?? "not reported")} |`,
    `| Guest memory | ${meta.guestMemoryMiB ? `${meta.guestMemoryMiB} MiB` : "not reported"} |`,
    `| Total duration | ${meta.totalMs ? `${(meta.totalMs / 1000).toFixed(1)} s` : "not measured"} |`,
    "",
    "## Summary",
    "",
    `${passed} passed, ${failed} failed, ${skipped} skipped.`,
    "",
    "| Probe | Result | Verdict | Duration |",
    "| --- | --- | --- | --- |",
    ...probes.map(
      (probe) =>
        `| ${cell(probe.title)} | ${marker(probe.status)} | ${cell(probe.detail)} | ${
          probe.durationMs === undefined ? "—" : `${(probe.durationMs / 1000).toFixed(2)} s`
        } |`,
    ),
    "",
    "## Details",
    "",
  ];

  for (const probe of probes) {
    lines.push(`### ${marker(probe.status)} — ${probe.title}`, "", probe.detail, "");
    if (probe.output && probe.output.trim().length > 0) {
      lines.push("```text", truncate(probe.output), "```", "");
    }
  }

  return `${lines.join("\n").trimEnd()}\n`;
}
